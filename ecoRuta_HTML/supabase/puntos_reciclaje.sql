-- Se ejecuta UNA sola vez en Supabase > SQL Editor, en tu proyecto de PRÁCTICA.
-- No va dentro de ningún .js y no se ejecuta desde el navegador.

-- PASO 1. Campos, tipos y restricciones.
create table public.puntos_reciclaje (
  id integer generated by default as identity primary key,
  nombre text not null check (char_length(btrim(nombre)) between 3 and 80),
  direccion text not null check (char_length(btrim(direccion)) between 3 and 120),
  horario text not null,
  materiales text[] not null,
  categorias text[] not null
    check (categorias <@ array['Papel','Plástico','Vidrio','Metal','Electrónicos']::text[]),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  activo boolean not null default true
);

-- PASO 2. Control de acceso por filas.
alter table public.puntos_reciclaje enable row level security;

-- PASO 3. Tabla NUEVA: quitamos privilegios iniciales y damos solo lectura a anon.
revoke all on table public.puntos_reciclaje from anon, authenticated;
grant select on table public.puntos_reciclaje to anon;

-- PASO 4. Lectura pública: son puntos de reciclaje pensados para mostrarse en un mapa.
-- No se abre INSERT, UPDATE ni DELETE al navegador (eso se decide en la clase 10).
create policy "lectura_publica_puntos"
on public.puntos_reciclaje
for select
to anon
using (true);

